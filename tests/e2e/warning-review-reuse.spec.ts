import { expect, test } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import { E2E_API_ORIGIN } from '../../playwright.config';
import { ephemeralWorkspaceHeaders, seedServerWorkspace } from './ephemeral';

test('C03 real warning approval reuse, invalidation, records and rendered revocation', async ({ page, request }) => {
  test.setTimeout(300_000);
  const out = path.resolve('test-results/claude-C03', `run-${randomUUID()}`);
  const mods = path.join(out, 'mods'), source = path.join(mods, 'forge_regression_lab'), game = path.join(out, 'game');
  fs.mkdirSync(source, { recursive: true }); fs.mkdirSync(path.join(game, 'extensions'), { recursive: true });
  fs.writeFileSync(path.join(game, 'X4.exe'), 'Inert scratch path marker; never executed.');
  const base = JSON.parse(fs.readFileSync('tests/fixtures/forge-regression/project.json', 'utf8'));
  const md = base.files.find((f: any) => f.path === 'md/forge_regression_lab.xml');
  const cleanMd = md.content;
  const warningMd = cleanMd.replace('</actions>', '<set_value name="$probe" exact="$x.forge_review_warning_a"/></actions>');
  md.content = warningMd;
  base.files.find((f: any) => f.path === 'ui/lab.lua').content = 'return {}\n';
  const write = (name: string, text: string) => { const p = path.join(source, name); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, text); };
  base.files.forEach((f: any) => write(f.path, f.content));
  const headers = await ephemeralWorkspaceHeaders(true);
  let call = 0; const checks: string[] = [];
  const post = async (route: string, body: unknown, authority = headers) => {
    const response = await request.post(E2E_API_ORIGIN + route, { headers: { ...authority, Connection: 'close', 'x-forge-operation-id': `forge_op_${randomUUID().replaceAll('-', '')}` }, data: body });
    const data = await response.json();
    // Key material never enters proof artifacts.
    if (route !== '/api/agent/keys') fs.writeFileSync(path.join(out, `${++call}-${route.split('/').pop()}.json`), JSON.stringify({ status: response.status(), data }, null, 2));
    return { status: response.status(), data };
  };
  expect((await post('/api/schema/config', { modWorkspacePath: mods, filesystemPath: path.join(game, 'extensions'), x4GamePath: game })).status).toBe(200);
  const imported = await post('/api/agent/mod-folder/import', { root: 'workspace', path: 'forge_regression_lab' });
  expect(imported.data.success).toBe(true); await seedServerWorkspace(imported.data.workspace);
  const key = async (scope: string, label: string) => {
    const r = await post('/api/agent/keys', { label, scope, ttl: '7d', workspaceId: headers['x-workspace-id'], clientId: headers['x-client-id'] });
    expect(r.status, JSON.stringify({ code: r.data.code, error: r.data.error })).toBe(200);
    return { ...headers, Authorization: `Bearer ${r.data.token}` };
  };
  const firstActor = await key('deploy', 'Original C03 reviewer'), secondActor = await key('deploy', 'Second C03 deployer');
  const reader = await key('read', 'C03 reader'), writer = await key('write', 'C03 writer');
  const route = '/api/agent/deploy-verify', target = { path: 'forge_regression_lab', deployFormat: 'loose' };
  const preview = async (authority = firstActor) => { const r = await post(route, { ...target, dryRun: true }, authority); expect(r.data.ok, JSON.stringify(r.data)).toBe(true); return r.data; };
  const identity = (p: any) => Object.fromEntries(['modId', 'sourceHash', 'artifactHash', 'bindingHash'].map(k => [`expected${k[0].toUpperCase()}${k.slice(1)}`, p[k]]));
  const apply = async (p: any, authority = firstActor, acceptances: unknown[] = []) => post(route, { ...target, ...identity(p), acceptances }, authority);
  const accept = (p: any) => [{ findingId: p.validation.evidence.findings.find((f: any) => f.code === 'scriptproperty.unknown' && f.message.includes('warning_a')).findingId,
    bindingHash: p.bindingHash, reason: 'Reviewed synthetic C03 warning against fixture; not a real mod approval.' }];
  const bytes = () => { const file = path.join(game, 'extensions/forge_regression_lab/md/forge_regression_lab.xml'); return fs.existsSync(file) ? createHash('sha256').update(fs.readFileSync(file)).digest('hex') : null; };
  const initial = await preview(); expect(initial.validation.review.counts.acceptedWarnings).toBe(0); expect(bytes()).toBeNull();
  const approved = await apply(initial, firstActor, accept(initial)); expect(approved.data.ok, JSON.stringify(approved.data)).toBe(true);
  expect(approved.data.validation.review.warningReviews.knownFindingIds).toHaveLength(1);
  expect(approved.data.validation.review.warningReviews.newFindingIds).toHaveLength(0);
  const original = approved.data.acceptanceRecords.find((r: any) => r.metadata.findingSeverity === 'warning'); expect(original).toBeDefined();
  checks.push('fresh-warning-explicit-approval', 'preview-no-target-write');
  const known = await preview(secondActor); expect(known.validation.review.counts.acceptedWarnings).toBe(1);
  expect(known.validation.review.warningReviews.knownFindingIds).toHaveLength(1);
  const reused = await apply(known, secondActor); expect(reused.data.ok, JSON.stringify(reused.data)).toBe(true);
  const reuseReceipt = reused.data.acceptanceRecords.find((r: any) => r.metadata.originalReceiptId === original.id);
  expect(reuseReceipt.status).toBe('committed'); expect(reuseReceipt.actor.id).not.toBe(original.actor.id);
  expect(reuseReceipt.metadata.originalActorId).toBe(original.actor.id); expect(reuseReceipt.metadata.reason).toBe(original.metadata.reason);
  expect(reused.data.deployRecord.authority.resources.some((r: any) => r.relativePath === `${reuseReceipt.id}.json` && r.beforeHash === reuseReceipt.hash)).toBe(true);
  expect(reused.data.validation.clean).toBe(false); checks.push('cross-agent-reuse', 'original-actor-reason-and-receipts', 'qualified-not-clean');
  const revokeBody = { receiptId: original.id, reviewScopeHash: known.validation.review.warningReviews.scopeHash, reason: 'Withdraw test review' };
  for (const authority of [reader, writer]) expect((await post('/api/agent/warning-reviews/revoke', revokeBody, authority)).status).toBe(403);
  expect((await post('/api/agent/warning-reviews/revoke', { ...revokeBody, actor: 'forged' }, secondActor)).status).toBe(400);
  expect((await post('/api/agent/warning-reviews/revoke', { ...revokeBody, reviewScopeHash: 'f'.repeat(64) }, secondActor)).status).toBe(409);
  const otherSource = path.join(mods, 'other_source'); fs.mkdirSync(otherSource);
  const foreign = structuredClone(imported.data.workspace); foreign.sourceStamp.dir = otherSource;
  await seedServerWorkspace(foreign);
  expect((await post('/api/agent/warning-reviews/revoke', revokeBody, secondActor)).data.code).toBe('REVIEW_WORKSPACE_MISMATCH');
  await seedServerWorkspace(imported.data.workspace);
  checks.push('read-write-forbidden', 'strict-input', 'wrong-scope-refused', 'other-workspace-source-refused');
  await page.addInitScript(() => { localStorage.setItem('x4_forge_experience_mode', 'expert'); localStorage.removeItem('x4_mod_studio_workspace'); localStorage.removeItem('x4_mod_studio_version'); });
  await page.goto('/'); await page.locator('[data-sidebar-tab="playtest"]').click();
  await page.getByTestId('verify-path-input').fill('forge_regression_lab');
  await page.getByTestId('deploy-verify-btn').click();
  const result = page.getByTestId('verify-result');
  await expect(result.getByTestId('deploy-review-title')).toHaveText('Deployed — accepted findings', { timeout: 90_000 });
  await result.getByTestId('deploy-review-title').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'qualified-deployment.png'), fullPage: true });
  const history = result.getByTestId('warning-review-history'); await history.locator('summary').click();
  await expect(history).toContainText('1 known'); await expect(history.getByRole('button', { name: 'Revoke review', exact: true })).toBeDisabled();
  await history.getByLabel('Warning review revocation reason').fill('Withdraw via actual rendered C03 control');
  await history.scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(out, 'known-review.png'), fullPage: true });
  const beforeRevoke = bytes(); await history.getByRole('button', { name: 'Revoke review', exact: true }).click();
  await expect(history.getByRole('status')).toContainText('Review revoked'); expect(bytes()).toBe(beforeRevoke);
  await history.getByRole('status').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(out, 'revoked-review.png'), fullPage: true });
  checks.push('actual-rendered-list-and-revoke', 'revoke-no-target-write');
  expect((await apply(known, secondActor)).status).toBe(409); expect(bytes()).toBe(beforeRevoke);
  const revoked = await preview(secondActor); expect(revoked.validation.review.counts.acceptedWarnings).toBe(0);
  expect(revoked.validation.review.warningReviews.rows.some((r: any) => r.state === 'revoked')).toBe(true);
  const recovered = await apply(revoked, secondActor, accept(revoked)); expect(recovered.data.ok).toBe(true);
  expect((await preview()).validation.review.counts.acceptedWarnings).toBe(1); checks.push('revoked-preview-refused', 'fresh-explicit-reapproval-recovery');
  const rulesPath = path.join(source, 'forge.rules.json');
  const previousRules = fs.existsSync(rulesPath) ? fs.readFileSync(rulesPath, 'utf8') : undefined;
  write('forge.rules.json', JSON.stringify({ version: 1, suppressions: [], contracts: { knownChains: [], wireKeys: [], expectedRegisters: [] } }));
  const rulesChanged = await preview(); expect(rulesChanged.validation.review.counts.acceptedWarnings).toBe(0);
  expect(rulesChanged.validation.review.warningReviews.rows.some((r: any) => r.state === 'invalidated')).toBe(true);
  if (previousRules === undefined) fs.unlinkSync(rulesPath); else write('forge.rules.json', previousRules);
  expect((await preview()).validation.review.counts.acceptedWarnings).toBe(1);
  checks.push('rules-byte-change-invalidates', 'exact-evidence-restoration-recovers');
  write('md/forge_regression_lab.xml', warningMd.replace('</actions>', '<set_value name="$second" exact="$x.forge_review_warning_b"/></actions>'));
  const changed = await preview(); expect(changed.validation.review.counts.acceptedWarnings).toBe(0);
  expect(changed.validation.review.counts.unacceptedWarnings).toBe(2);
  expect(changed.validation.review.warningReviews.rows.some((r: any) => r.state === 'invalidated')).toBe(true);
  const beforeStale = bytes(); expect((await apply(revoked)).status).toBe(409); expect(bytes()).toBe(beforeStale);
  checks.push('source-change-invalidation', 'new-warning-not-inherited', 'stale-source-no-write');
  write('md/forge_regression_lab.xml', cleanMd);
  const resolved = await preview(); expect(resolved.validation.review.counts.acceptedWarnings).toBe(0);
  expect(resolved.validation.review.warningReviews.rows.some((r: any) => r.state === 'resolved')).toBe(true);
  checks.push('resolved-review-visible');
  fs.writeFileSync(path.join(out, 'receipt.json'), JSON.stringify({ pass: true, checks, originalReceiptId: original.id, reuseReceiptId: reuseReceipt.id,
    sourceHash: reused.data.sourceHash, deployReceiptId: reused.data.deployRecord.id }, null, 2));
});
