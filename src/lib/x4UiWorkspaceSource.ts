const hasOwn = (value: object, key: string): boolean => Object.prototype.hasOwnProperty.call(value, key);

function deepFreeze<T>(value: T, seen: WeakSet<object> = new WeakSet<object>()): T {
  if (value === null || typeof value !== 'object') return value;
  const objectValue = value as unknown as object;
  if (seen.has(objectValue)) return value;
  seen.add(objectValue);
  const record = value as unknown as Record<PropertyKey, unknown>;
  for (const key of Reflect.ownKeys(record)) {
    deepFreeze(record[key], seen);
  }
  return Object.freeze(value);
}

function cloneClosedData<T>(
  value: T,
  seen: WeakMap<object, object> = new WeakMap<object, object>(),
  ownReplacement?: { readonly key: PropertyKey; readonly value: unknown }
): T {
  if (value === null || typeof value !== 'object') return value;
  const objectValue = value as unknown as object;
  if (seen.has(objectValue)) return seen.get(objectValue) as T;

  if (Array.isArray(value)) {
    const clonedArray = new Array(value.length) as unknown as T;
    Object.setPrototypeOf(clonedArray, Object.getPrototypeOf(value));
    seen.set(objectValue, clonedArray as unknown as object);
    for (const key of Reflect.ownKeys(value)) {
      if (key === 'length') continue;
      const descriptor = Object.getOwnPropertyDescriptor(value, key);
      if (!descriptor) continue;
      if ('value' in descriptor) descriptor.value = cloneClosedData(descriptor.value, seen);
      Object.defineProperty(clonedArray, key, descriptor);
    }
    const lengthDescriptor = Object.getOwnPropertyDescriptor(value, 'length');
    if (lengthDescriptor) Object.defineProperty(clonedArray, 'length', lengthDescriptor);
    return clonedArray;
  }

  const clonedObject = Object.create(Object.getPrototypeOf(value)) as Record<PropertyKey, unknown>;
  seen.set(objectValue, clonedObject);
  for (const key of Reflect.ownKeys(value)) {
    const descriptor = Object.getOwnPropertyDescriptor(value, key);
    if (!descriptor) continue;
    if ('value' in descriptor) {
      // Substitute only at this root, before defining a possibly read-only field.
      descriptor.value = cloneClosedData(key === ownReplacement?.key ? ownReplacement.value : descriptor.value, seen);
    }
    Object.defineProperty(clonedObject, key, descriptor);
  }
  if (ownReplacement && !Object.prototype.hasOwnProperty.call(value, ownReplacement.key)) {
    Object.defineProperty(clonedObject, ownReplacement.key, {
      value: cloneClosedData(ownReplacement.value, seen), enumerable: true, writable: true, configurable: true
    });
  }
  return clonedObject as T;
}

function utf8ByteLength(value: string): number {
  return new TextEncoder().encode(value).byteLength;
}

function splicePassthroughRecord(file: PassthroughFile, content: string): PassthroughFile {
  return hasOwn(file, 'bytes')
    ? { ...file, content, bytes: utf8ByteLength(content) }
    : { ...file, content };
}

function cloneWorkspaceForSplice(
  workspace: ModWorkspace,
  passthroughFiles: readonly PassthroughFile[]
): ModWorkspace {
  return cloneClosedData(workspace, new WeakMap<object, object>(), { key: 'passthroughFiles', value: passthroughFiles });
}

function freezeArray<T>(items: readonly T[]): readonly T[] {
  return Object.freeze([...items]);
}

function freezeObject<T extends object>(value: T): T {
  return Object.freeze(value);
}

function snapshotRecord(file: PassthroughFile): Omit<X4UiWorkspaceSourceRecord, 'workspaceIndex' | 'bundleIndex'> {
  return deepFreeze({
    path: file.path,
    ...(hasOwn(file, 'content') ? { content: file.content } : {}),
    ...(hasOwn(file, 'contentEncoding') ? { contentEncoding: file.contentEncoding } : {}),
    ...(hasOwn(file, 'reason') ? { reason: file.reason } : {}),
    ...(hasOwn(file, 'omitted') ? { omitted: file.omitted } : {}),
    ...(hasOwn(file, 'bytes') ? { bytes: file.bytes } : {})
  });
}

function sameRecord(
  left: PassthroughFile | X4UiWorkspaceSourceRecord | undefined,
  right: PassthroughFile | X4UiWorkspaceSourceRecord | undefined
): boolean {
  if (!left || !right) return false;
  return left.path === right.path
    && left.content === right.content
    && left.contentEncoding === right.contentEncoding
    && left.reason === right.reason
    && left.omitted === right.omitted
    && left.bytes === right.bytes;
}

function sameRecordArray(
  current: readonly PassthroughFile[] | undefined,
  expected: readonly X4UiWorkspaceSourceRecord[]
): boolean {
  if (!Array.isArray(current) || current.length !== expected.length) return false;
  return expected.every((record, index) => sameRecord(current[index], record));
}

function normalizeManifestPath(path: string): string {
  return path.replace(/\\/g, '/').replace(/^\/+/, '').toLowerCase();
}

function isLuaPassthroughPath(path: string): boolean {
  return /\.lua$/i.test(path.replace(/\\/g, '/'));
}

function uniqueGeneratedPaths(paths: readonly string[]): readonly string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const path of paths) {
    if (typeof path !== 'string' || path.length === 0) continue;
    const key = normalizeManifestPath(path);
    if (!key || seen.has(key)) continue;
    seen.add(key);
    result.push(path);
  }
  return freezeArray(result);
}

function activeUiWidgets(workspace: ModWorkspace): boolean {
  return Array.isArray(workspace.uiWidgets)
    && workspace.uiWidgets.some(widget => widget != null && widget.includeInBuild !== false);
}

function activeCustomLua(workspace: ModWorkspace): boolean {
  return typeof workspace.customLua === 'string' && workspace.customLua.trim().length > 0;
}

function compileFacts(
  workspace: ModWorkspace,
  generatedPathInputs: readonly string[],
  passthroughFiles: readonly PassthroughFile[]
): {
  readonly uiCompileEnabled: boolean;
  readonly activeUiWidgets: boolean;
  readonly activeCustomLua: boolean;
  readonly generatedRootUiXml: boolean;
  readonly generatedPaths: readonly string[];
  readonly generatedCollisions: readonly string[];
} {
  const uiCompileEnabled = workspace.compileSettings?.ui !== false;
  const widgets = activeUiWidgets(workspace);
  const customLua = activeCustomLua(workspace);
  const generatedRootUiXml = uiCompileEnabled && (widgets || customLua);
  const generatedPaths = uniqueGeneratedPaths([
    ...(generatedRootUiXml ? ['ui.xml'] : []),
    ...(uiCompileEnabled ? generatedPathInputs : [])
  ]);
  const generatedKeys = new Set(generatedPaths.map(normalizeManifestPath));
  const generatedCollisions = passthroughFiles
    .filter(file => generatedKeys.has(normalizeManifestPath(file.path)))
    .map(file => file.path);

  return {
    uiCompileEnabled,
    activeUiWidgets: widgets,
    activeCustomLua: customLua,
    generatedRootUiXml,
    generatedPaths,
    generatedCollisions: freezeArray(generatedCollisions)
  };
}

function compileInputFingerprint(
  workspace: ModWorkspace,
  generatedPathInputs: readonly string[]
): string | null {
  try {
    const fingerprint = JSON.stringify({
      compileSettings: workspace.compileSettings ?? null,
      uiWidgets: Array.isArray(workspace.uiWidgets) ? workspace.uiWidgets : null,
      customLua: workspace.customLua ?? null,
      generatedPathInputs
    });
    return fingerprint === undefined ? null : fingerprint;
  } catch {
    return null;
  }
}

function findRecordMatches(files: readonly PassthroughFile[], target: PassthroughFile): readonly number[] {
  const identityMatches = files
    .map((file, index) => file === target ? index : -1)
    .filter(index => index >= 0);
  if (identityMatches.length > 0) return freezeArray(identityMatches);
  return freezeArray(files
    .map((file, index) => sameRecord(file, target) ? index : -1)
    .filter(index => index >= 0));
}

function makeWorkspaceRecord(
  file: PassthroughFile,
  workspaceIndex: number | null,
  bundleIndex?: number
): X4UiWorkspaceSourceRecord {
  return deepFreeze({
    ...snapshotRecord(file),
    workspaceIndex,
    ...(bundleIndex === undefined ? {} : { bundleIndex })
  });
}

function selectedLuaRecords(
  workspaceFiles: readonly PassthroughFile[],
  options: X4UiWorkspaceSourceBuildOptions
): readonly SelectedLuaRecord[] {
  const explicit = options.passthroughLuaFiles ?? options.luaFiles;
  const records = explicit === undefined
    ? workspaceFiles.filter(file => typeof file.path === 'string' && isLuaPassthroughPath(file.path))
    : explicit;

  return freezeArray(records.map(record => {
    const matches = findRecordMatches(workspaceFiles, record);
    const workspaceIndex = matches.length === 1 ? matches[0] : null;
    return {
      record: makeWorkspaceRecord(record, workspaceIndex),
      workspaceIndex,
      mappingAmbiguous: matches.length > 1
    };
  }));
}

function buildState(
  workspace: ModWorkspace,
  options: X4UiWorkspaceSourceBuildOptions
): SourceBuildState {
  const workspaceFiles = Array.isArray(workspace.passthroughFiles)
    ? workspace.passthroughFiles
    : [];
  const rootIndexes = workspaceFiles
    .map((file, index) => typeof file?.path === 'string' && file.path.toLowerCase() === 'ui.xml' ? index : -1)
    .filter(index => index >= 0);
  const rootCandidates = freezeArray(rootIndexes.map(index => makeWorkspaceRecord(workspaceFiles[index], index)));
  const rootFile = rootCandidates.length === 1 ? rootCandidates[0] : null;
  const selectedLua = selectedLuaRecords(workspaceFiles, options);
  const materializedLua: {
    readonly selectedIndex: number;
    readonly bundleIndex: number;
    readonly record: X4UiWorkspaceSourceRecord;
  }[] = [];
  for (let selectedIndex = 0; selectedIndex < selectedLua.length; selectedIndex += 1) {
    const selected = selectedLua[selectedIndex];
    if (selected.record.omitted === true || typeof selected.record.content !== 'string') continue;
    materializedLua.push({
      selectedIndex,
      bundleIndex: materializedLua.length,
      record: makeWorkspaceRecord(selected.record, selected.workspaceIndex, materializedLua.length)
    });
  }

  const suppliedPaths = options.generatedPaths === undefined
    ? []
    : options.generatedPaths.filter(path => typeof path === 'string');

  return {
    workspaceFiles,
    rootCandidates,
    rootFile,
    selectedLua,
    materializedLua: freezeArray(materializedLua),
    generatedPathInputs: freezeArray(suppliedPaths)
  };
}

function addReason(
  reasons: X4UiWorkspaceSourceReason[],
  reason: X4UiWorkspaceSourceReason
): void {
  if (!reasons.includes(reason)) reasons.push(reason);
}

function bundleReasons(
  bundle: X4UiSourceBundle,
  state: SourceBuildState
): X4UiWorkspaceSourceReason[] {
  const reasons: X4UiWorkspaceSourceReason[] = [];
  if (!bundle.xml.parsed) addReason(reasons, 'malformed-xml');
  if (bundle.registrations.length === 0) addReason(reasons, 'no-registered-lua');

  for (const registration of bundle.registrations) {
    switch (registration.resolution) {
      case 'missing-file':
        addReason(reasons, 'missing-registered-lua');
        break;
      case 'duplicate-registration':
        addReason(reasons, 'duplicate-registered-lua');
        break;
      case 'ambiguous-source-file':
        addReason(reasons, 'ambiguous-registered-lua');
        break;
      case 'unsafe-traversal':
      case 'unsafe-absolute':
        addReason(reasons, 'unsafe-source-path');
        break;
      case 'missing-name':
      case 'invalid-path':
        addReason(reasons, 'invalid-source-registration');
        break;
      case 'malformed-xml':
        addReason(reasons, 'malformed-xml');
        break;
      case 'resolved':
        break;
    }
  }

  for (const diagnostic of bundle.diagnostics) {
    switch (diagnostic.code) {
      case 'lua-parse-failure':
        addReason(reasons, 'malformed-lua');
        break;
      case 'unsafe-lua-file':
        addReason(reasons, 'unsafe-source-path');
        break;
      case 'duplicate-supplied-lua-file':
        addReason(reasons, 'duplicate-supplied-lua');
        break;
      default:
        break;
    }
  }

  if (state.selectedLua.some(selected => selected.record.omitted === true || selected.record.content === undefined)) {
    addReason(reasons, 'omitted-lua-source');
  }
  if (state.selectedLua.some(selected => selected.mappingAmbiguous)) {
    addReason(reasons, 'ambiguous-passthrough-record');
  }
  if (state.selectedLua.some(selected => selected.workspaceIndex === null)) {
    addReason(reasons, 'passthrough-lua-not-in-workspace');
  }
  if (bundle.locked && reasons.length === 0) addReason(reasons, 'source-locked');
  return reasons;
}

function sourceDetail(status: X4UiWorkspaceSourceStatus, reason: X4UiWorkspaceSourceReason): string {
  switch (status) {
    case 'source-owned':
      return 'The accepted source bundle is the package-visible UI authority.';
    case 'generated-shadowing-source':
      return reason === 'generated-path-collision'
        ? 'Generated UI output claims a passthrough path; the generated file wins.'
        : 'Generated root ui.xml claims the passthrough menu; the generated manifest wins.';
    case 'unavailable':
      return reason === 'no-root-ui-xml'
        ? 'No exact extension-root ui.xml passthrough record was supplied.'
        : 'The workspace has no unambiguous usable root UI source record.';
    case 'locked':
      return 'The source bundle is present but locked by an explicit source or registration condition.';
  }
}

function compileProjection(
  status: X4UiWorkspaceSourceStatus,
  workspace: ModWorkspace,
  state: SourceBuildState,
  bundle: X4UiSourceBundle | null,
  projection: X4UiSourceBundleProjection | null
): X4UiWorkspaceSourceCompileProjection {
  const facts = compileFacts(workspace, state.generatedPathInputs, state.workspaceFiles);
  const authority: X4UiWorkspaceSourceAuthority = status === 'source-owned'
    ? 'source-owned'
    : status === 'generated-shadowing-source'
      ? 'generated-shadowing-source'
      : 'unavailable';
  const shippableProjection = status === 'source-owned' && bundle && projection ? projection : null;
  return deepFreeze({
    authority,
    uiCompileEnabled: facts.uiCompileEnabled,
    activeUiWidgets: facts.activeUiWidgets,
    activeCustomLua: facts.activeCustomLua,
    generatedRootUiXml: facts.generatedRootUiXml,
    generatedPaths: facts.generatedPaths,
    generatedCollisions: facts.generatedCollisions,
    shippableProjection,
    shippable: shippableProjection !== null
  });
}

