export const toSafeModId = (name: string): string => {
  const safe = name
    .toLowerCase()
    .replace(/[^a-z0-9_]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '');
  return safe || 'x4_md_studio_mod';
};

/** Resolve the artifact/deploy folder id using the existing imported-workspace precedence. */
export const resolveWorkspaceArtifactId = (
  workspace: { sourceFolder?: unknown; contentId?: unknown; name?: unknown } | null | undefined,
): string => {
  if (workspace && typeof workspace.sourceFolder === 'string' && workspace.sourceFolder) {
    const base = workspace.sourceFolder.replace(/[\\/]+$/, '').split(/[\\/]/).pop() || '';
    const fromFolder = toSafeModId(base);
    if (fromFolder) return fromFolder;
  }
  const cid = workspace?.contentId;
  return (typeof cid === 'string' && /^[A-Za-z][\w.-]*$/.test(cid))
    ? cid
    : toSafeModId(typeof workspace?.name === 'string' ? workspace.name : '');
};

/**
 * Workspace version → X4 content.xml version integer (X4 shows 100 as "1.00").
 * Audit #1 (2026-07-10): format-aware. A PURE INTEGER is treated as ALREADY being the X4
 * version and passes through untouched ("100" → "100"; the old blind ×100 turned it into
 * "10000" — a shipped-artifact corruption a modder using X4's own convention would hit).
 * Dotted versions keep the EXACT previous behavior (parseFloat×100: "1.0.0" → "100",
 * "1.2" → "120"), so every existing semver-authored mod compiles to the same number.
 */
export const toContentVersion = (value: string): string => {
  const raw = String(value || '').trim();
  if (/^\d+$/.test(raw)) return String(Math.max(1, parseInt(raw, 10))); // already X4 format
  const normalized = raw.match(/^\d+(?:\.\d+)?/)?.[0];
  const numericVersion = normalized ? Number.parseFloat(normalized) : 1;
  const contentVersion = Number.isFinite(numericVersion)
    ? Math.round(numericVersion * 100)
    : 100;

  return String(Math.max(1, contentVersion));
};

export const escapeXmlAttr = (str: string): string => {
  return (str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
};

export const escapeXmlText = (str: string): string => {
  return (str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
};

export const toTFileName = (file: TFileNameInput): string => {
  const explicitName = String(file?.fileName || '').trim();
  // Imported names identify existing source files; normalize only newly generated names.
  if (explicitName) return explicitName;

  const languageId = String(file?.languageId || '44').replace(/\D/g, '') || '44';
  return `0001-l${languageId.padStart(3, '0')}.xml`;
};

export const generateContentXML = (modId: string, workspace: ModWorkspace): string => {
  const today = new Date().toISOString().slice(0, 10);
  const displayName = workspace.name || modId;
  const description = workspace.description || 'Generated by X4 Forge';
  const author = workspace.author || 'X4 Forge';
  // Emit declared dependencies so they survive regeneration (previously dropped → the mod
  // silently no-op'd APIs in-game and the dependency analyzer kept warning).
  const depLines = (((workspace as any).dependencies || []) as Array<{ id?: string; version?: string; optional?: boolean }>)
    .filter(d => d && d.id)
    .map(d => {
      const attrs = [`id="${escapeXmlAttr(d.id!)}"`];
      if (d.version) attrs.push(`version="${escapeXmlAttr(d.version)}"`);
      if (d.optional) attrs.push(`optional="true"`);
      return `  <dependency ${attrs.join(' ')} />`;
    });
  return `<?xml version="1.0" encoding="utf-8"?>\n<content id="${escapeXmlAttr(modId)}" name="${escapeXmlAttr(displayName)}" description="${escapeXmlAttr(description)}" author="${escapeXmlAttr(author)}" version="${toContentVersion(workspace.version)}" date="${today}" save="0" enabled="1">\n  <text language="44" name="${escapeXmlAttr(displayName)}" description="${escapeXmlAttr(description)}" author="${escapeXmlAttr(author)}" />\n${depLines.length ? depLines.join('\n') + '\n' : ''}</content>\n`;
};

/**
 * #65 — provenance-aware aiscript namespacing. Returns the FINAL aiscript name for
 * export: a bare authored name is prefixed `<modId>.<name>` (so two studio mods don't
 * ship colliding generic filenames); a name that already carries the modId prefix — or
 * any name marked final via `alreadyNamespaced` (e.g. an imported foreign-namespaced
 * script) — is returned unchanged. Pure + idempotent: f(f(x)) === f(x).
 */
export const namespaceAiScriptName = (name: string, modId: string, alreadyNamespaced = false): string => {
  const n = (name || '').trim();
  if (!n || !modId) return n;
  const prefix = `${modId}.`;
  if (alreadyNamespaced || n.startsWith(prefix)) return n;
  return `${prefix}${n}`;
};

export const compileScriptToXML = (script: AIBehaviorScript): string => {
  let xml = `<?xml version="1.0" encoding="utf-8"?>\n`;
  xml += `<aiscript name="${escapeXmlAttr(script.name)}" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="aiscripts.xsd">\n`;
  xml += `  <!-- X4 Foundations Autopilot & Task Script Behavior -->\n`;
  xml += `  <!-- Generated visually using X4 Forge Behaviors Suite -->\n`;
  xml += `  <params>\n`;
  (script.params || []).forEach((p) => {
    xml += `    <param name="${escapeXmlAttr(p.name)}" type="${escapeXmlAttr(p.type)}" default="${escapeXmlAttr(p.defaultValue)}" comment="${escapeXmlAttr(p.comment)}" />\n`;
  });
  xml += `  </params>\n`;

  if (script.interrupts && script.interrupts.length > 0) {
    xml += `  <interrupts>\n`;
    script.interrupts.forEach((int) => {
      xml += `    <handler event="${escapeXmlAttr(int.event)}">\n`;
      xml += `      <actions>\n`;
      if (int.action === 'flee') {
        xml += `        <run_script name="'move.flee'" />\n`;
      } else if (int.action === 'dock_at_safety') {
        xml += `        <run_script name="'move.dockat'" />\n`;
      } else {
        xml += `        <write_to_logbook text="'Interrupt event fired: ${escapeXmlAttr(int.event)}'" />\n`;
      }
      xml += `      </actions>\n`;
      xml += `    </handler>\n`;
    });
    xml += `  </interrupts>\n`;
  }

  xml += `  <attention min="${escapeXmlAttr(script.attentionLevel || 'low')}">\n`;
  xml += `    <actions>\n`;
  xml += `      <label name="start" />\n`;

  (script.actions || []).forEach((act) => {
    xml += `      <!-- Action: ${escapeXmlText(act.label)} -->\n`;
    switch (act.command) {
      case 'move_to':
        xml += `      <move_to object="this.ship" destination="${escapeXmlAttr(act.properties.destination || '$target')}" forceposition="false" finishonfound="true">\n`;
        xml += `        <interrupt_after_time time="10s" />\n`;
        xml += `      </move_to>\n`;
        break;
      case 'flee':
        xml += `      <run_script name="'move.flee'" />\n`;
        break;
      case 'shoot':
        xml += `      <shoot_at object="this.ship" target="${escapeXmlAttr(act.properties.target || '$enemy')}" turretmode="attackhostile" />\n`;
        break;
      case 'dock_at':
        xml += `      <dock_at object="this.ship" station="${escapeXmlAttr(act.properties.station || '$station')}" />\n`;
        break;
      case 'wait':
        if (act.properties.exact) {
          xml += `      <wait exact="${escapeXmlAttr(act.properties.exact)}" />\n`;
        } else {
          xml += `      <wait min="${escapeXmlAttr(act.properties.min || '2s')}" max="${escapeXmlAttr(act.properties.max || '10s')}" />\n`;
        }
        break;
      case 'find_objects':
        xml += `      <find_object name="$targets" class="class.${escapeXmlAttr(act.properties.class || 'ship')}" space="player.sector" multiple="true" />\n`;
        break;
      case 'custom_xml':
        xml += `      ${act.properties.rawXml || '<!-- custom nodes -->'}\n`;
        break;
    }
  });

  xml += `    </actions>\n`;
  xml += `  </attention>\n`;
  xml += `</aiscript>`;
  return xml;
};

export const compileWaresXML = (wares: WareDef[]): string => {
  let xml = `<?xml version="1.0" encoding="utf-8"?>\n`;
  xml += `<diff>\n`;
  xml += `  <!-- XML Diff Patch adding to core wares database file: libraries/wares.xml -->\n`;
  xml += `  <add sel="/wares">\n`;
  wares.forEach((item) => {
    const tagsAttr = item.tags ? ` tags="${escapeXmlAttr(item.tags)}"` : '';
    const productionMethod = item.productionMethod || 'default';
    const productionNameAttr = item.productionName ? ` name="${escapeXmlAttr(item.productionName)}"` : '';
    const primaryWares = Array.isArray(item.primaryWares)
      ? item.primaryWares.filter((ware) => String(ware?.ware || '').trim() && Number(ware?.amount) > 0)
      : [];

    xml += `    <ware id="${escapeXmlAttr(item.id)}" name="${escapeXmlAttr(item.name)}" description="${escapeXmlAttr(item.description)}" transport="${escapeXmlAttr(item.transport)}" volume="${item.volume}"${tagsAttr}>\n`;
    xml += `      <price min="${item.minPrice}" average="${item.avgPrice}" max="${item.maxPrice}" />\n`;
    xml += `      <production time="${item.prodTime}" amount="${item.prodAmount}" method="${escapeXmlAttr(productionMethod)}"${productionNameAttr}`;
    if (primaryWares.length === 0) {
      xml += ` />\n`;
    } else {
      xml += `>\n`;
      xml += `        <primary>\n`;
      primaryWares.forEach((ware) => {
        xml += `          <ware ware="${escapeXmlAttr(ware.ware)}" amount="${escapeXmlAttr(String(ware.amount))}" />\n`;
      });
      xml += `        </primary>\n`;
      xml += `      </production>\n`;
    }
    xml += `    </ware>\n`;
  });
  xml += `  </add>\n`;
  xml += `</diff>`;
  return xml;
};

